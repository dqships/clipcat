// Turns the help pages in the repo's docs/ folder into lib/docs.generated.mjs:
// each page's HTML for /docs and its Markdown for agents. The output is
// committed, because Vercel builds this folder on its own; a test fails when
// it's out of date. Run `npm run docs` from the repo root after editing docs/.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseDocs, renderDoc, rewriteLinks } from "../../../docs/pages.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const DOCS_DIR = join(here, "..", "..", "..", "docs");
export const OUT = join(here, "..", "lib", "docs.generated.mjs");

/** Where a page lives on the site. */
export const docPath = (slug) => (slug ? `/docs/${slug}` : "/docs");

/** The generated module's text, from the pages as they are now. */
export function docsModule(dir = DOCS_DIR) {
  const files = Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith(".md")).map((f) => [f, readFileSync(join(dir, f), "utf8")]));
  const pages = parseDocs(files).map((doc) => {
    // The page template sets the H1, so the HTML starts after it.
    const body = doc.markdown.replace(/^# .+\n+/, "");
    return {
      path: docPath(doc.slug),
      nav: doc.slug ? doc.h1 : "Help",
      title: doc.title,
      description: doc.description,
      h1: doc.h1,
      updated: doc.updated,
      html: renderDoc(body, (slug, hash) => `${docPath(slug)}${hash}`),
      markdown: rewriteLinks(doc.markdown, (slug, hash) => `${docPath(slug)}.md${hash}`),
    };
  });
  return [
    "// Generated by scripts/docs.mjs from the repo's docs/ folder. Don't edit it: edit docs/, then run `npm run docs`.",
    "",
    `export const DOCS = ${JSON.stringify(pages, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, docsModule());
  console.log(`wrote ${OUT}`);
}
